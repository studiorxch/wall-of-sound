  // ── Opacity — hosted style, pattern/soft-line layers ──────────────────────
  // 0729_MAPS_Visual_Property_Authority_Audit — the bridge/tunnel/road
  // "-navigation" layers carry line-pattern (a sprite baked into the hosted
  // Mapbox Studio style — see wall/runtimes/broadcastStyleCleanup.js's own
  // audit()/apply(), which this discovery deliberately mirrors) and several
  // tunnel "-case" layers carry a soft line-opacity. Pattern CHOICE isn't
  // wired (swapping sprite images baked into the remote style is out of
  // scope — see the audit report), but opacity is a genuine, independently
  // controllable paint property on the same layers, discovered the same
  // live-from-map.getStyle() way as color.
  var OPACITY_PAINT_PROPS = {
    'fill':   ['fill-opacity'],
    'line':   ['line-opacity'],
    'circle': ['circle-opacity'],
  };

  function _hasPattern(paint) {
    return 'line-pattern' in paint || 'fill-pattern' in paint;
  }

  function _discoverPatternOpacity(map) {
    var records = [];
    if (!map || typeof map.getStyle !== 'function') return records;
    var style;
    try { style = map.getStyle(); } catch (e) { return records; }
    var layers = (style && style.layers) || [];
    layers.forEach(function (layer) {
      if (_isBuildingLayer(layer)) return;
      var paint = layer.paint || {};
      // Scope: only layers that actually carry a pattern or a soft (<1)
      // opacity — not every fill/line layer's opacity, to avoid ballooning
      // the schema with properties that were never flagged as part of this
      // audit's "pattern/soft-line" trace target.
      var opacityProp = (OPACITY_PAINT_PROPS[layer.type] || [])[0];
      if (!opacityProp || !(opacityProp in paint)) return;
      var opacityValue = paint[opacityProp];
      if (typeof opacityValue !== 'number') return; // expression-driven opacity — not a flat editable number
      if (!_hasPattern(paint) && opacityValue >= 1) return; // fully-opaque, no-pattern layers are out of this audit's scope
      records.push({
        id:             'mapbox-opacity.' + layer.id + '.' + opacityProp,
        label:          _readableLabel(layer, opacityProp),
        group:          _classifyGroup(layer),
        source:         'mapbox-style',
        sourceLocation: 'hosted Mapbox Studio style — discovered live via map.getStyle()',
        sourceObject:   layer.id,
        sourceProperty: opacityProp,
        currentValue:   String(opacityValue),
        valueKind:      'opacity',
        displayColor:   null,
        editable:       true,
        transitionable: true,
        status:         'wired',
        ownerModule:    'mapbox-style:' + layer.id,
        notes: _hasPattern(paint)
          ? 'Pattern-bearing layer (line-pattern/fill-pattern sprite baked into the hosted style) — pattern choice itself is not editable, opacity is.'
          : 'Soft-line layer (partial default opacity in the hosted style).',
      });
    });
    return records;
  }

