// Builds the Phase 1 property registry for the MAPS Geographic Style system.
//
// Scope (Phase 1 — narrow, per 0729A build direction):
//   WIRED   — hosted Mapbox base-map layers (discovered live via map.getStyle(),
//             excluding building/fill-extrusion layers, which stay with the
//             existing per-building authoring authority), and the route
//             line/marker colors in mapboxOperatorRenderer/routePlannerRuntime/
//             routePanel.
//   DEFERRED / VESTIGIAL — everything else this audit found (actors, vessels,
//             aircraft, traffic, orbital-mode-only rendering, broader atmosphere,
//             sky shader, general application UI, per-building overrides, the
//             legacy MapStyleAuthority). Reported for completeness, not wired —
//             no setter APIs were added to those modules in this build.
//
// 0729_MAPS_Visual_Property_Authority_Audit additions — new WIRED properties:
//   line-opacity/fill-opacity on the hosted style's pattern-bearing and
//   soft-line layers (bridge/tunnel/road "-navigation" — see
//   _discoverPatternOpacity; the pattern sprite itself is baked into the
//   remote Mapbox Studio style, not addImage()'d locally, so pattern CHOICE
//   stays out of scope, opacity doesn't). Everything else this audit found
//   (OverlayRuntime's transit/isolation canvas layers, building illustration/
//   material/surface-texture patterns, the dormant harbor-geometry debug
//   renderer, and hardcoded cyan/teal literals outside this registry) is
//   cataloged honestly in getDeferredAudit() below, not wired — see the
//   audit report for the full inventory and why.
//
// vehicle.hero.* / hud.environmental.* / overlay.atmosphere-composite.enabled
// all moved OUT of this registry in 0729D Phase 2/3 — they are now discovered
// by the standalone vehicleStyleRegistry.js (Vehicles library) and
// overlayStyleRegistry.js (Overlays library), per the spec's "do not force
// vehicle materials or HUD/overlay effects into Geographic Styles."
//
// A raw property record is NOT tied to Mapbox specifically — see
// GeographicStylePropertySource below — but the base-map group is generated by
// walking the live style (map.getStyle()) rather than a hand-typed layer list,
// per the "runtime discovery over hand-authored records" build direction.
//
// Placement: wall/systems/presentation/mapsGeographicStyleRegistry.js
// Load: AFTER mapboxViewportRuntime.js, heroVehicleRenderer.js,
//       routePlannerRuntime.js, routePanel.js, mapboxOperatorRenderer.js,
//       environmentalTelemetryHUD.js. BEFORE mapsGeographicStyleAuthority.js.
// ──────────────────────────────────────────────────────────────────────────────
